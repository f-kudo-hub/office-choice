/**
 * 月額会員（¥2,980）へ毎月お届けする原稿を作る
 *
 * ── 会員がお金を払う理由 ────────────────────────────────────
 * jGrantsは誰でも無料で見られる。**それでもお金を払ってもらえるのは、
 * 「探す・見張る・思い出す」を代わりにやるから。**
 * だからこの原稿の値打ちは、件数の多さではなく **絞り込みと締切の近さ** にある。
 *
 *   ① 今すぐ動かないと間に合わないもの（締切が近い順）
 *   ② 先月には無かったもの（新しく出たもの）
 *   ③ 全国どこでも使えるもの（地域で外れない）
 *
 * ── 絞り込みの考え方 ────────────────────────────────────────
 * 読者は「従業員10〜100人の会社で総務を兼任している決裁者」。
 * **全部を並べない。**220件を全部出すのは、何も選んでいないのと同じ。
 * 地域で自分に関係ないものが8割を占めると、読むのをやめる。
 *
 * ── 事実の扱い ──────────────────────────────────────────────
 * ・**上限額の「未公表」を「0円」と書かない**（APIが0を返しただけ）
 * ・**要約や解釈を足さない。**制度の中身はこちらで言い換えず、公式へ誘導する
 *   （言い換えて間違えると、締切を逃すより重い）
 * ・**初回は「新着」を出さない。**比べる相手がいないだけなのに
 *   「今月220件が新しく出ました」と書けば、それは嘘になる
 * ・出典リンクを必ず1件ずつ付ける
 *
 * 使い方： node tools/会員向けの原稿を作る.mjs
 *          （先に node tools/補助金を集める.mjs を実行しておく）
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ここ = dirname(fileURLToPath(import.meta.url))
const 作業場 = join(ここ, '..')
const 元データ = join(作業場, 'データ', '補助金_最新.json')
const 出し先 = join(作業場, '会員向け')

if (!existsSync(元データ)) {
  console.error('データ/補助金_最新.json がありません。先に node tools/補助金を集める.mjs を実行してください')
  process.exit(1)
}

const 元 = JSON.parse(readFileSync(元データ, 'utf8'))
const 全件 = 元.補助金 ?? []
const 今日 = 元.集めた日

const 円 = n => '¥' + Number(n).toLocaleString('ja-JP')
const 上限 = n => (Number(n) > 0 ? 円(n) : '未公表')
const 残り = 締切 => Math.round((new Date(締切) - new Date(今日)) / 86400000)
const 日数差 = (a, b) => Math.round((new Date(a) - new Date(b)) / 86400000)

/** 今月（YYYY-MM）。号数として使う */
const 今月 = 今日.slice(0, 7)

/** 表を1つ作る */
function 表(rows) {
  let s = '| 締切 | 残り | 補助金 | 上限額 | 対象地域 |\n| --- | ---: | --- | ---: | --- |\n'
  for (const r of rows) {
    s += `| ${r.締切 ?? '—'} | ${r.締切 ? 残り(r.締切) + '日' : '—'} | [${r.名称}](${r.出典}) | ${上限(r.上限額)} | ${r.対象地域 ?? '—'} |\n`
  }
  return s + '\n'
}

const 締切あり = 全件.filter(r => r.締切).sort((a, b) => a.締切.localeCompare(b.締切))

// ① 今すぐ動くもの（14日以内）
const 急ぎ = 締切あり.filter(r => 残り(r.締切) >= 0 && 残り(r.締切) <= 14)

// ② 新しく出たもの（この30日で初めて見つけたもの）
const 新着 = 全件
  .filter(r => r.見つけた日 && 日数差(今日, r.見つけた日) <= 30)
  .sort((a, b) => String(b.見つけた日).localeCompare(String(a.見つけた日)))

// **初回だけは、全部が「新着」に見える。**まだ比べる相手がいないだけで、
// 220件が今月新しく出たわけではない。**そこを黙って「新着220件」と出すと嘘になる。**
const 見張り開始 = 全件.map(r => r.見つけた日).filter(Boolean).sort()[0] ?? 今日
const 比べられる = 新着.length < 全件.length

// ③ 全国で使えるもの（地域で外れない・締切が近い順）
const 全国 = 締切あり.filter(r => r.対象地域 === '全国' && 残り(r.締切) >= 0).slice(0, 20)

let md = `# 今月の補助金レポート（${今月}号）\n\n`
md += `> **${今日} 時点で受付中：${全件.length}件**\n`
md += `> 出典：デジタル庁「Jグランツ」公開API（公的な一次情報）\n\n`
md += `このレポートは毎朝データを取り直して作っています。**前号の写しではありません。**\n\n`
md += `⚠️ 上限額の「未公表」は、公式データが金額を持っていないという意味です。**0円ではありません。**\n`
md += `⚠️ 制度の中身はこちらで言い換えていません。**申請の前に必ず公式ページをご確認ください**（各行のリンク先）。\n\n`
md += `---\n\n`

md += `## ① 今すぐ動かないと間に合わないもの（14日以内・${急ぎ.length}件）\n\n`
md += 急ぎ.length ? 表(急ぎ) : '今月は14日以内に締切のものがありません。\n\n'

if (比べられる) {
  md += `## ② 先月には無かったもの（この30日で新しく出た・${新着.length}件）\n\n`
  md += 新着.length
    ? 表(新着.slice(0, 25)) + (新着.length > 25 ? `※ ほかに ${新着.length - 25}件あります\n\n` : '')
    : 'この30日で新しく出たものはありませんでした。\n\n'
} else {
  md += `## ② 先月には無かったもの\n\n`
  md += `**今号はこの欄をお出しできません。**見張りを始めたのが ${見張り開始} で、`
  md += `まだ「前はどうだったか」と比べられるだけの日数が経っていないためです。\n\n`
  md += `いま受付中の${全件.length}件を「すべて新着」として並べることもできますが、`
  md += `それは事実ではないので出しません。**次号から、本当に新しく出たものだけが並びます。**\n\n`
}

md += `## ③ 全国どこでも使えるもの（締切が近い順・上位${全国.length}件）\n\n`
md += 全国.length ? 表(全国) : '該当がありません。\n\n'

md += `---\n\n`
md += `### 来月に向けて\n\n`
md += `締切が過ぎたものは自動で一覧から消え、新しく公募が始まったものが入ります。\n`
md += `**「先月見たときには無かったもの」だけを②に出します。**毎月ここだけ見ていただければ、見落としません。\n\n`
md += `### この記事について\n\n`
md += `データはデジタル庁「Jグランツ」の公開APIから毎朝自動で取得しています。\n`
md += `内容の正誤は各補助金の公式ページが優先します。**申請の可否や採択を保証するものではありません。**\n`

if (!existsSync(出し先)) mkdirSync(出し先, { recursive: true })
writeFileSync(join(出し先, `${今月}_今月の補助金レポート.md`), md, 'utf8')

console.log(`${今月}号を作りました`)
console.log(`  ① 14日以内に締切：${急ぎ.length}件`)
console.log(`  ② 新着：${比べられる ? 新着.length + '件' : `まだ出しません（見張り開始 ${見張り開始}・比べる相手がいない）`}`)
console.log(`  ③ 全国で使える　：${全国.length}件（上位20件を掲載）`)
console.log(`→ 会員向け/${今月}_今月の補助金レポート.md`)
