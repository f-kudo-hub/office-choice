/**
 * 月額会員（¥2,980）へ毎月お届けする原稿を作る
 *
 * ── 会員がお金を払う理由 ────────────────────────────────────
 * jGrantsは誰でも無料で見られる。**それでもお金を払ってもらえるのは、
 * 「探す・見張る・思い出す」を代わりにやるから。**
 * だからこの原稿の値打ちは、件数の多さではなく **絞り込みと締切の近さ** にある。
 *
 *   ① 今すぐ動かないと間に合わないもの（締切が近い順）
 *   ② 先月には無かったもの（新しく出たもの）
 *   ③ 全国どこでも使えるもの（地域で外れない）
 *
 * ── 出すもの ────────────────────────────────────────────────
 *   会員向け/YYYY-MM_今月の補助金レポート.md        … 表つき（保管用）
 *   会員向け/YYYY-MM_今月の補助金レポート_note用.txt … 箇条書き（noteに貼る用）
 *
 * **noteのエディタは表に対応していない。**markdownの表を貼ると罫線が
 * 文字のまま並んで読めなくなるので、貼る用は箇条書きにする。
 * **数字は作り直さない。**同じ変数から2つ出す（作り直すと2つの原稿がズレる）。
 *
 * ── 事実の扱い ──────────────────────────────────────────────
 * ・**上限額の「未公表」を「0円」と書かない**（APIが0を返しただけ）
 * ・**要約や解釈を足さない。**制度の中身はこちらで言い換えず、公式へ誘導する
 *   （言い換えて間違えると、締切を逃すより重い）
 * ・**初回は「新着」を出さない。**比べる相手がいないだけなのに
 *   「今月220件が新しく出ました」と書けば、それは嘘になる
 * ・出典リンクを必ず1件ずつ付ける
 *
 * 使い方： node tools/会員向けの原稿を作る.mjs
 *          （先に node tools/補助金を集める.mjs を実行しておく）
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ここ = dirname(fileURLToPath(import.meta.url))
const 作業場 = join(ここ, '..')
const 元データ = join(作業場, 'データ', '補助金_最新.json')
const 出し先 = join(作業場, '会員向け')

if (!existsSync(元データ)) {
  console.error('データ/補助金_最新.json がありません。先に node tools/補助金を集める.mjs を実行してください')
  process.exit(1)
}

const 元 = JSON.parse(readFileSync(元データ, 'utf8'))
const 全件 = 元.補助金 ?? []
const 今日 = 元.集めた日

const 円 = n => '¥' + Number(n).toLocaleString('ja-JP')
const 上限 = n => (Number(n) > 0 ? 円(n) : '未公表')
const 残り = 締切 => Math.round((new Date(締切) - new Date(今日)) / 86400000)
const 日数差 = (a, b) => Math.round((new Date(a) - new Date(b)) / 86400000)
const NL = '\n'

/** 今月（YYYY-MM）。号数として使う */
const 今月 = 今日.slice(0, 7)

/** 表を1つ作る（保管用のmarkdown） */
function 表(rows) {
  let s = '| 締切 | 残り | 補助金 | 上限額 | 対象地域 |' + NL + '| --- | ---: | --- | ---: | --- |' + NL
  for (const r of rows) {
    s += `| ${r.締切 ?? '—'} | ${r.締切 ? 残り(r.締切) + '日' : '—'} | [${r.名称}](${r.出典}) | ${上限(r.上限額)} | ${地域(r.対象地域)} |` + NL
  }
  return s + NL
}

/** 同じ中身を箇条書きにする（noteに貼る用） */
function 箇条書き(rows) {
  return rows
    .map(r => {
      const d = r.締切 ? `${r.締切}（あと${残り(r.締切)}日）` : '締切の記載なし'
      return `■ ${r.名称}` + NL + `　締切：${d}／上限：${上限(r.上限額)}／対象：${地域(r.対象地域)}` + NL + `　${r.出典}`
    })
    .join(NL + NL)
}

/**
 * 対象地域を読める長さにする。
 *
 * jGrantsは対象地域を都道府県の羅列で返すことがあり、
 * **47都道府県が1行に並ぶと、その行だけで画面が埋まって読めなくなる**
 * （実例：令和８年度酒類業振興支援事業費補助金）。
 * 数が多いときは件数にまとめる。**「全国」と書き換えない**
 * （47都道府県ぶんの列挙と、制度が「全国」と名乗っているのは別物）。
 */
function 地域(v) {
  const s = (v ?? '').trim()
  if (!s) return '—'
  const 県 = s.split('/').map(x => x.trim()).filter(Boolean)
  if (県.length <= 3) return 県.join('・')
  return `${県.length}都道府県`
}

const 締切あり = 全件.filter(r => r.締切).sort((a, b) => a.締切.localeCompare(b.締切))

// ① 今すぐ動くもの（明日から14日以内）
//
// **「あと0日」を載せない。**その日のうちに締切るものは、会員が読んだ時にはもう終わっている。
// 「今すぐ動けば間に合う」と言って間に合わないものを並べるのは、いちばんやってはいけないこと。
const 急ぎ = 締切あり.filter(r => 残り(r.締切) >= 1 && 残り(r.締切) <= 14)

// ② 新しく出たもの（この30日で初めて見つけたもの）
const 新着 = 全件
  .filter(r => r.見つけた日 && 日数差(今日, r.見つけた日) <= 30)
  .sort((a, b) => String(b.見つけた日).localeCompare(String(a.見つけた日)))

// **初回だけは、全部が「新着」に見える。**まだ比べる相手がいないだけで、
// 220件が今月新しく出たわけではない。**そこを黙って「新着220件」と出すと嘘になる。**
const 見張り開始 = 全件.map(r => r.見つけた日).filter(Boolean).sort()[0] ?? 今日
const 比べられる = 新着.length < 全件.length

// ③ 全国で使えるもの（地域で外れない・締切が近い順）
// **ここも「あと0日」を外す。**①と同じ理由（読んだ時にはもう終わっている）
const 全国 = 締切あり.filter(r => r.対象地域 === '全国' && 残り(r.締切) >= 1).slice(0, 20)

const 新着なし文 =
  `今号はこの欄をお出しできません。見張りを始めたのが ${見張り開始} で、` +
  `まだ「前はどうだったか」と比べられるだけの日数が経っていないためです。` + NL +
  `いま受付中の${全件.length}件を「すべて新着」として並べることもできますが、` +
  `それは事実ではないので出しません。次号から、本当に新しく出たものだけが並びます。`

// ── 保管用（表つきmarkdown）──────────────────────────────
let md = `# 今月の補助金レポート（${今月}号）` + NL + NL
md += `> **${今日} 時点で受付中：${全件.length}件**` + NL
md += `> 出典：デジタル庁「Jグランツ」公開API（公的な一次情報）` + NL + NL
md += `このレポートは毎朝データを取り直して作っています。**前号の写しではありません。**` + NL + NL
md += `⚠️ 上限額の「未公表」は、公式データが金額を持っていないという意味です。**0円ではありません。**` + NL
md += `⚠️ 制度の中身はこちらで言い換えていません。**申請の前に必ず公式ページをご確認ください**（各行のリンク先）。` + NL + NL
md += `---` + NL + NL

md += `## ① 今すぐ動けば間に合うもの（14日以内・${急ぎ.length}件）` + NL + NL
md += 急ぎ.length ? 表(急ぎ) : '今月は14日以内に締切のものがありません。' + NL + NL

if (比べられる) {
  md += `## ② 先月には無かったもの（この30日で新しく出た・${新着.length}件）` + NL + NL
  md += 新着.length
    ? 表(新着.slice(0, 25)) + (新着.length > 25 ? `※ ほかに ${新着.length - 25}件あります` + NL + NL : '')
    : 'この30日で新しく出たものはありませんでした。' + NL + NL
} else {
  md += `## ② 先月には無かったもの` + NL + NL + 新着なし文 + NL + NL
}

md += `## ③ 全国どこでも使えるもの（締切が近い順・上位${全国.length}件）` + NL + NL
md += 全国.length ? 表(全国) : '該当がありません。' + NL + NL

md += `---` + NL + NL
md += `### この記事について` + NL + NL
md += `データはデジタル庁「Jグランツ」の公開APIから毎朝自動で取得しています。` + NL
md += `内容の正誤は各補助金の公式ページが優先します。**申請の可否や採択を保証するものではありません。**` + NL
md += `**申請の代行は行いません**（行政書士・社会保険労務士の業務にあたるため）。` + NL

// ── noteに貼る用（箇条書き）────────────────────────────────
const 線 = '━━━━━━━━━━━━━━━━'
let nt = `${今日} 時点で受付中：${全件.length}件` + NL
nt += `出典：デジタル庁「Jグランツ」公開API（公的な一次情報）` + NL + NL
nt += `毎朝データを取り直して作っています。前号の写しではありません。` + NL
nt += `上限額の「未公表」は、公式データが金額を持っていないという意味です。0円ではありません。` + NL
nt += `制度の中身はこちらで言い換えていません。申請の前に必ず公式ページをご確認ください。` + NL + NL

nt += 線 + NL + `① 今すぐ動けば間に合うもの（14日以内・${急ぎ.length}件）` + NL + 線 + NL + NL
nt += (急ぎ.length ? 箇条書き(急ぎ) : '今月は14日以内に締切のものがありません。') + NL + NL

nt += 線 + NL + `② 先月には無かったもの` + NL + 線 + NL + NL
nt += (比べられる
  ? (新着.length
      ? 箇条書き(新着.slice(0, 15)) + (新着.length > 15 ? NL + NL + `※ ほかに ${新着.length - 15}件あります` : '')
      : 'この30日で新しく出たものはありませんでした。')
  : 新着なし文) + NL + NL

nt += 線 + NL + `③ 全国どこでも使えるもの（締切が近い順・上位${全国.length}件）` + NL + 線 + NL + NL
nt += (全国.length ? 箇条書き(全国) : '該当がありません。') + NL + NL

nt += 線 + NL + NL
nt += `データはデジタル庁「Jグランツ」の公開APIから毎朝自動で取得しています。` + NL
nt += `内容の正誤は各補助金の公式ページが優先します。申請の可否や採択を保証するものではありません。` + NL
nt += `申請の代行は行いません（行政書士・社会保険労務士の業務にあたるため）。` + NL

if (!existsSync(出し先)) mkdirSync(出し先, { recursive: true })
writeFileSync(join(出し先, `${今月}_今月の補助金レポート.md`), md, 'utf8')
writeFileSync(join(出し先, `${今月}_今月の補助金レポート_note用.txt`), nt, 'utf8')

console.log(`${今月}号を作りました`)
console.log(`  ① 14日以内に締切：${急ぎ.length}件`)
console.log(`  ② 新着：${比べられる ? 新着.length + '件' : `まだ出しません（見張り開始 ${見張り開始}・比べる相手がいない）`}`)
console.log(`  ③ 全国で使える　：${全国.length}件（上位20件を掲載）`)
console.log(`→ 会員向け/${今月}_今月の補助金レポート.md（保管用・表つき）`)
console.log(`→ 会員向け/${今月}_今月の補助金レポート_note用.txt（noteに貼る用・箇条書き）`)
