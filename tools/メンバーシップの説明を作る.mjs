/**
 * noteのメンバーシップ説明文を、いまの数字で作り直す
 *
 * ── なぜ機械で作るか ────────────────────────────────────────
 * 2026-09-08 常務「やっぱ2980円は高いね」。
 * **高く見えていたのは金額ではなく、「何を防ぐのか」が書かれていなかったから。**
 * 前の説明文は「毎月1回、補助金レポートをお届けします」で始まっていた。
 * これはサービスの説明であって、買う理由ではない。
 *
 * 買う理由は1行で言える：**締切を1件見逃した損は、月額の何十年分にもなる。**
 * ただしその「損」は実データから出さないと嘘になるので、ここで毎回数え直す。
 *
 * ⚠ **説明文に数字を固定で書かない。**受付中の件数も中央値も毎日動く。
 *   手で書くと、その日から少しずつ嘘になる。だから毎月、貼る直前に作り直す。
 *   （同じ理由で「◯◯件が新しく出ました」は初回に出さない＝比べる相手がいない）
 *
 * ── 事実の扱い ──────────────────────────────────────────────
 * ・上限額の「未公表」を0円として数えない（中央値が壊れる）
 * ・**国の巨大事業（数十億円）を代表値に使わない。**読者は従業員10〜100人の会社で、
 *   そこに商用車電動化の295億円を見せても、自分の話だと思えない。
 *   5,000万円以下に絞った中央値を使う（現実に手が届く帯）
 * ・申請の可否・採択は保証しない。代行はしない（行政書士・社労士の業務）
 *
 * 使い方： node tools/メンバーシップの説明を作る.mjs
 *          （先に node tools/補助金を集める.mjs）
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ここ = dirname(fileURLToPath(import.meta.url))
const 作業場 = join(ここ, '..')
const 元データ = join(作業場, 'データ', '補助金_最新.json')

if (!existsSync(元データ)) {
  console.error('データ/補助金_最新.json がありません。先に node tools/補助金を集める.mjs を実行してください')
  process.exit(1)
}

const 元 = JSON.parse(readFileSync(元データ, 'utf8'))
const 全件 = 元.補助金 ?? []
const 集めた日 = 元.集めた日

const 円 = n => '¥' + Number(n).toLocaleString('ja-JP')
/** 読みやすさのため「300万円」の形にする。⚠ noteの説明欄は太字にできないので記号も使わない */
const 万円 = n => {
  const v = Number(n)
  if (v >= 100_000_000) return (v / 100_000_000).toLocaleString('ja-JP') + '億円'
  if (v >= 10_000) return (v / 10_000).toLocaleString('ja-JP') + '万円'
  return v.toLocaleString('ja-JP') + '円'
}
const 残り = 締切 => Math.round((new Date(締切) - new Date(集めた日)) / 86400000)

/** 中央値。偶数個なら真ん中2つの平均 */
function 中央値(xs) {
  if (xs.length === 0) return 0
  const s = [...xs].sort((a, b) => a - b)
  const m = Math.floor(s.length / 2)
  return s.length % 2 ? s[m] : Math.round((s[m - 1] + s[m]) / 2)
}

const 上限額あり = 全件.map(r => Number(r.上限額) || 0).filter(n => n > 0)
// ⚠ 数十億円の国家事業を混ぜると、中央値が読者の現実から離れる
const 手の届く帯 = 上限額あり.filter(n => n <= 50_000_000)
const 代表額 = 中央値(手の届く帯)

const 一週間以内 = 全件.filter(r => r.締切 && 残り(r.締切) >= 0 && 残り(r.締切) <= 7).length

const 月額 = 2980
const 年額 = 月額 * 12
const 何年分 = Math.round(代表額 / 年額)

const 本文 = `補助金は、締切を過ぎたら1円も戻りません。

${集めた日} の時点で、国と自治体をあわせて${全件.length}件が受付中です。
そのうち${一週間以内}件は、7日以内に締切が来ます。

上限額が公表されているもののうち、${万円(50_000_000)}以下に絞った${手の届く帯.length}件の中央値は${万円(代表額)}。
1件見逃すと、このメンバーシップの約${何年分}年分にあたります。

情報が無いわけではありません。デジタル庁の「Jグランツ」で誰でも無料で見られます。
足りていないのは、${全件.length}件の中から自社に関係のあるものを毎月拾い出す時間です。
総務を兼任されている方に、その時間はありません。そこを代わりにやります。

▼毎月1回、お届けするもの
① 14日以内に締切が来るもの
② 先月には無かった、新しく出たもの
③ 全国どこでも使えるもの（地域で外れない）

▼データについて
デジタル庁「Jグランツ」の公開データから毎朝自動で取得しています。
公的な一次情報で、まとめサイトの写しではありません。全件に公式ページへのリンクを添えます。

▼1ヶ月は無料です
最初の号を読んでから決められます。合わなければ、その月のうちにやめられます。

▼締切カレンダーは無料で見られます
https://soumu-choice.com/hojo/
毎朝、公開データから自動で作り直しています。中身を見てからお決めください。

▼お約束
制度の内容をこちらで言い換えません（言い換えて間違えると、締切を逃すより重いため）。
申請の可否や採択を保証するものではありません。
申請の代行は行いません（行政書士・社会保険労務士の業務にあたるため）。
`

const 出し先 = join(作業場, '会員向け', '00_メンバーシップ説明_note用.txt')
writeFileSync(出し先, 本文, 'utf8')

console.log(`受付中 ${全件.length}件／7日以内 ${一週間以内}件`)
console.log(`${万円(50_000_000)}以下 ${手の届く帯.length}件の中央値 ${万円(代表額)} ＝ 月額${円(月額)}の約${何年分}年分`)
console.log(`書き出しました： 会員向け/00_メンバーシップ説明_note用.txt`)
