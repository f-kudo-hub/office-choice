/**
 * 副業サイト「オフィスの選びかた」の毎朝の点検
 * ---------------------------------------------------------------------------
 * 常務のご指示（2026-09-01）：
 *   「しっかり自動で毎日動いて収益を上げているか！そこを毎日しっかり管理して！
 *     ダメな場合は何か手を打って！忘れずにお願い！副業だけどこれも主戦場だ！」
 *
 * **見るのは3つだけ。**
 *   ① 自動更新が動いたか（補助金＝毎朝／記事＝毎朝）
 *   ② サイトが生きているか・ページが増えているか
 *   ③ 収益につながる線（提携先・記事の本数）
 *
 * **「動いていない」と「確認できていない」を混ぜません。**
 * GitHubに聞けなかったときは、そう出します。無事と点検漏れは別物です。
 *
 * 使い方： node tools/毎朝の点検.mjs
 * 結果は 00_点検結果.md に書き出します（このリポジトリの中。作業場には書きません）
 */
import { execSync } from 'node:child_process'
import { writeFileSync, readFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// **どこから呼ばれても同じ答えを返す。**作業場（00_ClaudeCode）から絶対パスで
// 呼ばれると、相対パスの `ls 記事` や `git ls-files` が空振りして
// 「記事0本・ページ数えられません」と出ていました（2026-09-02 に直した）
const ここ = dirname(fileURLToPath(import.meta.url))
process.chdir(join(ここ, '..'))

const リポ = 'f-kudo-hub/office-choice'
const サイト = 'https://soumu-choice.com/'
const 今 = new Date(new Date().toLocaleString('en-US', { timeZone: 'Asia/Tokyo' }))
const 今日 = 今.toLocaleDateString('sv-SE')

const gh = (path) => {
  try { return JSON.parse(execSync(`gh api "${path}"`, { encoding: 'utf8', stdio: ['ignore','pipe','ignore'] })) }
  catch { return null }
}

// 設定は1か所から読む。**点検の中に値を書き写さない**（写した瞬間に古くなる）
const 設定 = JSON.parse(readFileSync(join(ここ, '..', '設定.json'), 'utf8'))

const 行 = []
const 要対応 = []
const 出す = (s) => 行.push(s)

出す(`# オフィスの選びかた｜毎朝の点検`)
出す('')
出す(`**${今日} ${今.getHours()}時 時点**`)
出す('')

/* ── ① 自動更新 ────────────────────────────────── */
出す('## 自動で動いているか')
出す('')
const 一覧 = gh(`repos/${リポ}/actions/workflows`)
if (!一覧) {
  出す('- ⚠ **点検できていません**（GitHubに聞けませんでした）')
  要対応.push('GitHubに聞けず、自動更新を確認できていません')
} else {
  for (const [名, パス, 間隔] of [
    ['補助金の更新', 'subsidy-refresh', '毎朝6時'],
    ['毎日の記事', 'post-daily', '毎朝7時'],
  ]) {
    const w = 一覧.workflows.find(x => x.path.includes(パス))
    if (!w) { 出す(`- ⚠ **${名}**：ワークフローが見つかりません`); 要対応.push(`${名}のワークフローがありません`); continue }
    if (w.state !== 'active') { 出す(`- ⚠ **${名}**：止まっています（${w.state}）`); 要対応.push(`${名}が止まっています`); continue }
    const runs = gh(`repos/${リポ}/actions/workflows/${w.id}/runs?per_page=5`)
    const 最新 = runs?.workflow_runs?.[0]
    if (!最新) { 出す(`- **${名}**（${間隔}）：まだ1度も走っていません`); continue }
    const 経過 = Math.floor((Date.now() - new Date(最新.created_at)) / 3600000)

    // **まだ走っている途中のものを「失敗」と書かない。**
    // conclusion は終わるまで null で、status を代わりに読むと in_progress が
    // そのまま失敗に見えます（2026-09-02、自分で入れた点検が誤報を出しました）
    if (最新.status !== 'completed') {
      出す(`- … **${名}**（${間隔}）：いま走っています（${最新.status}）`)
      continue
    }

    const 結果 = 最新.conclusion
    const 印 = 結果 === 'success' ? '○' : '✗'
    出す(`- ${印} **${名}**（${間隔}）：最後は ${String(最新.created_at).slice(0,16).replace('T',' ')} UTC・${結果}（${経過}時間前）`)
    if (結果 !== 'success') 要対応.push(`${名}が失敗しています（${結果}）`)
    // **定期実行の枠が本当に叩かれているかを見る。**手動だけ通っていても「動いている」ではない。
    // ワークフローの文法が壊れていると、GitHubは登録せず、schedule の回が1件も出ません
    // （2026-09-02、if: が二重で丸ごと登録されていませんでした）
    const 定期 = runs.workflow_runs.filter(r => r.event === 'schedule')
    if (定期.length === 0) {
      // **作りたてのうちは、まだ最初の時刻が来ていないだけ。**
      // ここで鳴らすと、直した翌日は必ず誤報になります（2026-09-02 に出しました）。
      // 丸1日ぶん待ってから鳴らせば、本当に登録されていない場合だけ残ります
      const 若さ = Math.floor((Date.now() - new Date(w.created_at)) / 3600000)
      if (若さ < 30) {
        出す(`  - まだ定期実行の時刻が来ていません（この仕掛けは${若さ}時間前にできたばかり）`)
      } else {
        出す(`  - ⚠ 直近5回に**定期実行が1件もありません**（手で走らせた分だけです）`)
        要対応.push(`${名}の定期実行が登録されていません（文法エラーの疑い）`)
      }
    }
    // 毎朝のものが30時間以上動いていなければ、止まっている
    if (パス === 'subsidy-refresh' && 経過 > 30) 要対応.push(`補助金の更新が${経過}時間動いていません`)
    // 毎朝のものが30時間以上動いていなければ、止まっている
    if (パス === 'post-daily' && 経過 > 30) 要対応.push(`毎日の記事が${経過}時間動いていません`)
  }
}

/* ── ①-b **記事が本当に増えたか**（2026-09-07 追加）─────────────────
   ⚠ **「動いた」と「仕事をした」は別物です。**
   2026-09-04〜09-07 の4日間、`post-daily` は毎朝 success で終わっていたのに、
   記事は1本も増えていませんでした。「今日はもう書いた」と誤判定して
   素通りしていたためです（見張りが `docs` を見ており、先に走る補助金の更新が
   毎朝 `docs` を書き換えていた）。
   **上の点検は「走ったか・失敗しなかったか」しか見ていないので、
   この壊れ方は永遠に異常なしのままでした。**
   だからここで、**最後に記事が増えた日**を直接見ます。 */
出す('')
/* ── ①-c **土台が壊れていないか**（2026-09-07 追加）─────────────────
   ⚠ **今日だけで、失敗として現れない壊れ方が3つ起きた。**
     ・組み立て直すと docs/CNAME が消えた（放置なら翌朝ドメインが外れてサイトごと落ちた）
     ・Search Console の所有権確認ファイルも同じ性質（消えると所有権が外れる）
     ・公開の条件に抜けがあり、直しても反映されない状態だった
   **どれもエラーを出さない。**画面には何も出ないまま、静かに壊れる。
   だから毎朝、**外から実物を叩いて**確かめる。 */
出す('')
出す('## 土台')
出す('')
{
  const 見る = [
    ['トップ',                 'https://soumu-choice.com/',                              'html'],
    ['サイトマップ',           'https://soumu-choice.com/sitemap.xml',                   'xml'],
    ['robots.txt',             'https://soumu-choice.com/robots.txt',                    'robots'],
    ['所有権の確認ファイル',   'https://soumu-choice.com/google5be523a40969bb3f.html',   'text'],
  ]
  for (const [名, url, 型] of 見る) {
    try {
      const r = await fetch(url, { redirect: 'follow' })
      const 本文 = await r.text()
      let ok = r.ok
      let 補足 = ''
      // **200だけでは足りない。**中身が期待どおりかまで見る
      if (ok && 型 === 'xml' && !本文.includes('<loc>')) { ok = false; 補足 = '（中身にURLが無い）' }
      if (ok && 型 === 'robots' && !/Sitemap:\s*https:\/\/soumu-choice\.com/.test(本文)) {
        ok = false; 補足 = '（サイトマップの宣言が無い）'
      }
      if (ok && 型 === 'text' && !本文.includes('google-site-verification')) { ok = false; 補足 = '（中身が違う）' }
      if (ok && 型 === 'html' && !本文.includes('cloudflareinsights') && !本文.includes('gtag')) {
        ok = false; 補足 = '（計測タグが消えている）'
      }
      出す(`- ${ok ? '○' : '✗'} ${名}　HTTP ${r.status}${補足}`)
      if (!ok) 要対応.push(`土台がこわれています：${名} HTTP ${r.status}${補足}`)
    } catch (e) {
      出す(`- ✗ ${名}　読めませんでした`)
      要対応.push(`土台を確かめられませんでした：${名}`)
    }
  }
  // 独自ドメインの札。**消えると翌朝サイトごと落ちる**
  try {
    const c = readFileSync('docs/CNAME', 'utf8').trim()
    const ok = c === 'soumu-choice.com'
    出す(`- ${ok ? '○' : '✗'} docs/CNAME　${c || '（空）'}`)
    if (!ok) 要対応.push(`docs/CNAME がおかしい（${c}）`)
  } catch {
    出す('- ✗ docs/CNAME　**ありません**')
    要対応.push('docs/CNAME が消えています（このままだとドメインが外れます）')
  }
}

出す('## 記事が増えているか')
出す('')
try {
  const 最後 = execSync('git log -1 --format=%cI -- 記事', { encoding: 'utf8' }).trim()
  if (!最後) {
    出す('- 記事の履歴が読めませんでした')
    要対応.push('記事が増えているかを確かめられませんでした')
  } else {
    const 日 = Math.floor((Date.now() - new Date(最後)) / 86400000)
    const 日付 = new Date(最後).toLocaleDateString('sv-SE', { timeZone: 'Asia/Tokyo' })
    出す(`- 最後に記事が増えたのは **${日付}**（${日}日前）`)
    // 毎日1本の約束なので、2日空いたらおかしい（1日は実行の遅れで起こりうる）
    if (日 >= 2) {
      出す(`- 🔴 **${日}日ぶん、記事が増えていません。**実行は成功していても、中身が出ていません。`)
      要対応.push(`記事が${日}日ぶん増えていません（実行は成功しているのに中身が出ていない）`)
    } else {
      出す('- ○ 増えています')
    }
  }
} catch {
  出す('- 記事の履歴が読めませんでした')
  要対応.push('記事が増えているかを確かめられませんでした')
}

/* ── ② サイトの中身 ──────────────────────────────── */
出す('')
出す('## サイト')
出す('')
try {
  const 数 = execSync('git ls-files docs | grep -c "\.html$"', { encoding: 'utf8' }).trim()
  出す(`- 公開ページ：**${数}枚**`)
} catch { 出す('- 公開ページ：数えられませんでした') }
try {
  const 記事 = execSync('ls 記事 | wc -l', { encoding: 'utf8' }).trim()
  出す(`- 記事：**${記事}本**`)
} catch {}
try {
  const 提携 = JSON.parse(readFileSync('提携先.json', 'utf8'))
  const n = Array.isArray(提携) ? 提携.length : Object.values(提携)[0]?.length ?? '?'
  出す(`- 提携先：**${n}件**`)
} catch {}

/* ── 検索の言葉（Search Console） ──────────────────── */
// 2026-09-02 常務のご指示「（データが）出たら朝の点検で拾えるようにしておいて」。
//
// **GA4は「来た人」しか見えません。**「検索結果に出たのに来なかった」が見えないと、
// 記事を何本増やしても当てずっぽうになります。そこを見るのが Search Console。
//
// **催促はしません。**サイトマップを送った直後に急かしても、Google側にまだ数字がありません。
// 数字が溜まる頃（14日後）から声をかけ、それでも来ない日（28日後）だけ要対応にします。
出す('')
出す('## 検索の言葉')
出す('')
const サイトマップ送信日 = new Date('2026-09-02T00:00:00+09:00')
const 送信から = Math.floor((Date.now() - サイトマップ送信日) / 86400000)

let 検索の結果 = ''
try {
  検索の結果 = execSync('node "' + join(ここ, '検索の言葉を読む.mjs') + '"', { encoding: 'utf8' }).trim()
} catch (e) { 検索の結果 = '' }

if (/まだCSVがありません/.test(検索の結果) || 検索の結果 === '') {
  if (送信から < 14) {
    出す(`- サイトマップを送って **${送信から}日**。Google側にまだ数字が溜まっていない頃です。**急ぎません。**`)
  } else {
    出す('- ⏳ **Search Console の書き出し（CSV）が `データ/` にありません。**')
    出す('  🔗 https://search.google.com/search-console →「検索パフォーマンス」→ 右上「エクスポート」→ CSV')
    出す('  zipを展開して、中のCSVを丸ごと `データ/` に入れてください。ファイル名は問いません。')
    出す('  **これが無いと、どの記事のどの言葉を直せばよいか分かりません。**')
    if (送信から >= 28) 要対応.push(`Search Console のCSVが未取得（サイトマップ送信から${送信から}日）`)
  }
} else {
  出す('- ○ 読めています。**次に直す記事は `00_検索の言葉.md`** にあります。')
  for (const l of 検索の結果.split(/\r?\n/)) 出す('  ' + l.trim())
  if (/要対応/.test(検索の結果)) 要対応.push('検索で出ているのに選ばれていない言葉があります（00_検索の言葉.md）')
}

