/* Kindleの原稿を組む（記事 → 1冊のEPUB下書き）
 *
 * なぜ作ったか（2026-09-11 常務のご指示）
 *   「ありとあらゆる形で自動化できるものは全部自動化して、
 *    どの自動化が早く多く稼げるか！検証もできる！財布となる入口が少なすぎる！」
 *
 *   ⚠ **いま入口はGoogle検索1本で、そこが詰まっています**（240ページ中2ページしか載っていない）。
 *   Kindleは**Amazon内検索**という、Googleとまったく別の経路です。
 *   **Googleに載らなくても、こちらは人が来ます。**
 *   しかも印税70%で、1冊500円なら1冊350円。単発の送客より単価が高い。
 *
 * ⚠ **記事をそのまま並べるだけにはしません。**
 *   ①「はじめに」と「おわりに」を足し、②章立てを付け、③**本の中でしか読めない部分**を作る。
 *   そのまま出すと、**サイトと同じ文がAmazonにも並ぶ**ことになり、
 *   本としての価値も、サイトの独自性も、両方薄まります。
 *
 * ⚠ **サイトへの導線は入れますが、アフィリエイトリンクは入れません。**
 *   KDPの規約で、本文中のアフィリエイトリンクは禁じられています。
 *   入れるのは自サイトへのリンクだけ（印付き＝どれだけ来たか測れる）。
 *
 * 使い方: node tools/Kindleの原稿を組む.mjs
 * 出すもの: Kindle原稿/ （原稿.md・表紙の指示.md・出版の手順.md）
 */
import fs from 'node:fs'
import path from 'node:path'

const 出し先 = 'Kindle原稿'
const 記事の場所 = 'docs/kiji'
const サイト = 'https://soumu-choice.com'
const 印 = '?utm_source=kindle&utm_medium=ebook'

/* ── 記事を読む ────────────────────────────────── */
function タグを外す(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/g, '')
    .replace(/<style[\s\S]*?<\/style>/g, '')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function 記事を1本読む(道) {
  const html = fs.readFileSync(道, 'utf8')
  const 題 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1]?.replace(/<[^>]+>/g, '').trim()
  /* 本文は <article> か <main> の中だけ。ヘッダーやフッターを本に混ぜない */
  const 本体 = (html.match(/<article[\s\S]*?<\/article>/) || html.match(/<main[\s\S]*?<\/main>/) || [html])[0]
  /* 節ごとに拾う。h2 を章の中の見出しにする */
  const 節 = []
  const re = /<h2[^>]*>([\s\S]*?)<\/h2>([\s\S]*?)(?=<h2|$)/g
  let m
  while ((m = re.exec(本体))) {
    const 見出し = m[1].replace(/<[^>]+>/g, '').trim()
    const 中身 = タグを外す(m[2])
    if (見出し && 中身) 節.push({ 見出し, 中身 })
  }
  return { 題, 節, slug: path.basename(道, '.html'), 字数: タグを外す(本体).length }
}

let 道たち
try {
  道たち = fs.readdirSync(記事の場所).filter(f => f.endsWith('.html')).map(f => path.join(記事の場所, f))
} catch {
  console.error(`⚠ ${記事の場所} が読めません。先に記事を作ってください。`)
  process.exit(1)
}

const 記事たち = 道たち.map(記事を1本読む).filter(a => a.題 && a.節.length)
if (!記事たち.length) {
  console.error('⚠ 読める記事がありませんでした。')
  process.exit(1)
}

/* ── 本の形に組む ──────────────────────────────── */
const 書名 = '中小企業の総務が、契約の前に確かめること'
const 副題 = `${記事たち.length}の判断基準`

const 行 = []
行.push(`# ${書名}`, '', `## ${副題}`, '', '---', '')

/* ⚠ **「はじめに」は、本にしかない文。**
   ここが無いと、記事を並べただけの本になる。 */
行.push('## はじめに', '',
  'この本は、中小企業の総務・管理部門の方が、**契約書に判を押す前に確かめること**を集めたものです。',
  '',
  '複合機のリース、社用車、法人携帯、クラウド会計、社会保険労務士との顧問契約——',
  'どれも「よく分からないまま、勧められた条件で契約してしまう」ことが起きやすい領域です。',
  '',
  '**一度契約すると、数年単位で毎月お金が出ていきます。**',
  'しかも、途中でやめると違約金がかかるものが多い。',
  '**だから、判を押す前の数分が、いちばん効きます。**',
  '',
  'この本には、答えは書いてありません。書いてあるのは**確かめる順番**です。',
  '会社によって正解が違うためです。ただ、**確かめる順番は、どの会社でも同じ**です。',
  '',
  '各章は独立しています。**いま契約しようとしているものの章だけ**読んでください。',
  '', '---', '')

const 目次 = []
記事たち.forEach((a, i) => {
  目次.push(`${i + 1}. ${a.題}`)
})
行.push('## 目次', '', ...目次.map(x => `- ${x}`), '', '---', '')

記事たち.forEach((a, i) => {
  行.push(`# 第${i + 1}章　${a.題}`, '')
  a.節.forEach(s => {
    行.push(`## ${s.見出し}`, '', s.中身, '')
  })
  行.push('---', '')
})

/* ⚠ **「おわりに」も本にしかない文。**
   ここで自サイトへ送る。印を付けてあるので、何人来たか測れる。 */
行.push('## おわりに', '',
  'ここまでお読みいただき、ありがとうございました。',
  '',
  'この本に載せた基準は、**契約の条件が変わると古くなります。**',
  '補助金の締切や、各サービスの料金体系は、毎年のように変わるためです。',
  '',
  `最新の内容は、[オフィスの選びかた](${サイト}/${印}) で更新しています。`,
  `**補助金の締切は毎朝自動で更新**しており、[いま使える補助金チェッカー](${サイト}/hojo/checker.html${印}) から、`,
  '自社が使えるものを絞り込めます。',
  '',
  '**誤りを見つけられたら、お知らせいただけると助かります。**次の版で直します。',
  '')

fs.mkdirSync(出し先, { recursive: true })
const 原稿 = 行.join('\n')
fs.writeFileSync(path.join(出し先, '原稿.md'), 原稿, 'utf8')

/* ── 表紙の指示 ───────────────────────────────── */
fs.writeFileSync(path.join(出し先, '表紙の指示.md'), `# 表紙（Kindleの表紙は 1600×2560px）

⚠ **Kindleの表紙は、検索結果では親指の爪ほどの大きさで並びます。**
その大きさで**書名が読めること**だけが要件です。凝った絵は、その大きさでは消えます。

## 指定

- 地：**濃い紺**（#1B2A3A）
- 書名：**白・太いゴシック・特大**。画面の上から1/3に置く
- 副題：書名の下に、**書名の3分の1の大きさ**で
- 帯のように、下に**朱色（#C0341C）の横棒**を1本
- 絵は入れない

## 文字

- 書名：**${書名}**
- 副題：${副題}

⚠ **Amazonの表紙に、価格や「ベストセラー」などの文言を入れてはいけません**（KDP規約）。
`, 'utf8')

/* ── 出版の手順（常務にお願いする分だけ） ──────────────── */
fs.writeFileSync(path.join(出し先, '出版の手順.md'), `# 出版の手順（${new Date().toLocaleDateString('ja-JP')}）

⚠ **KDPのアカウント作成と、銀行口座・税情報の登録は、常務にしかできません。**
（安全の決まりで、クロは口座や本人確認を扱えません）

## 1回だけ（常務）

1. https://kdp.amazon.co.jp/ でアカウントを作る（Amazonのアカウントがあればそのまま使えます）
2. **口座情報と税に関する情報**を入れる（ここが済まないと出版できません）

## 毎回（クロ）

3. \`原稿.md\` を EPUB に変換して提出
4. 表紙を作って提出
5. 価格を決める

## ⚠ 価格について

| 価格帯 | 印税 | 1冊あたり |
| --- | ---: | ---: |
| ¥250〜¥1,250 | **70%** | 例：¥500 → **¥350** |
| それ以外 | 35% | 例：¥500 → ¥175 |

**¥250〜¥1,250 に収めること。**外すと印税が半分以下になります。

⚠ **Kindle Unlimited（KDPセレクト）に入れると、読まれたページ数でも収入が入ります。**
ただし**90日間、他で売れなくなります**（独占契約）。
いまは他で売る予定が無いので、入れて問題ありません。

## この本の中身

- 章：**${記事たち.length}章**
- およその字数：**${記事たち.reduce((a, b) => a + b.字数, 0).toLocaleString('ja-JP')}字**
`, 'utf8')

