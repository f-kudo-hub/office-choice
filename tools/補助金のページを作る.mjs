/**
 * 補助金1件につき1ページを作る（ロングテール集客の本体）
 *
 * ── なぜこれを作るか ──────────────────────────────────────────
 * いまの10記事は「勤怠管理システムの乗り換え」など、検索する人は多いが
 * 競合が強すぎる言葉を狙っている。開設したばかりのサイトは、そこには出ない。
 * 実際、A8の今月は imp 0 / click 0。**人が1人も来ていないから0円。**
 *
 * 一方、受付中の補助金は220件あり、**1件ずつの名前がそのまま検索語**になる。
 *   「令和8年度神奈川県小規模事業者デジタル化支援推進事業費補助金」
 * この言葉で検索する人は、まさに今それを申請しようとしている人で、
 * しかも大手メディアは個別の自治体補助金を追わない。**競合がいない。**
 *
 * ── ⚠️ ここを外すと、サイトごと検索から消える ────────────────
 * 「中身の薄いページを自動で大量に置く」はGoogleのスパムポリシー
 * （scaled content abuse）に当たる。数を出すこと自体は違反ではないが、
 * **1ページずつに独自の価値が無いと違反になる。**そこで、
 *
 *   1. 公式データ（Jグランツ＝一次情報）をそのまま表に出す
 *   2. その上に、公式には無い中身を必ず足す：
 *        ・補助率と上限額から逆算した「自己負担の目安」（このページだけの計算）
 *        ・締切から逆算した「いつ動き出すか」の日付（このページだけの計算）
 *        ・その用途で実際に何が買えるか
 *        ・同じ地域で同じ時期に使える似た制度（このページだけの組み合わせ）
 *   3. 制度の内容を言い換えない。**公式へ誘導する**
 *      （言い換えて間違えるほうが、書かないより重い）
 *   4. 広告表示は機械的に入れる（ステマ規制）
 *   5. 締切が過ぎたら自動で「終了しました」に変え、検索避け（noindex）にして
 *      サイトマップからも外す。**古い情報を残さない**
 *
 * ── 出す件数を絞る理由 ────────────────────────────────────────
 * 220件ぜんぶは作らない。**読者に対して答えが出せるものだけ**にする。
 * 「スポーツ・文化支援」の補助金のページを作っても、中小企業の総務には関係がなく、
 * こちらも紹介できる商材が無い。答えの無いページは、読者にとっても検索にとっても薄い。
 *
 * 使い方： tools/サイトを組み立てる.mjs から呼ばれる（単体では動かさない）
 */
