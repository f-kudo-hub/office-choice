/* 売り物：補助金の締切カレンダー（note の買い切り ¥300）の原稿を組む
 *
 * なぜ作ったか（2026-09-13 常務のご承認「はい」）
 *   月額¥2,980のメンバーシップは**会員0人**。0人に売る導線を磨いても、
 *   磨けたかどうかが分からない。**まず1人目を作るほうが早い。**
 *   値段は ¥300 〔クロ決定〕。理由は下の「値段の決め方」に書いた。
 *
 * ⚠ **売るのはデータではなく、整理です。**
 *   元はデジタル庁「Jグランツ」の公開データで、誰でも無料で見られます。
 *   **そのことを、無料で読める側にはっきり書きます。**隠して売らない。
 *   お金をいただくのは「都道府県別に締切順で並べ、上限額と自己負担の目安と
 *   逆算の段取りを添えて、1本にまとめたこと」に対してです。
 *
 * ⚠ **常務にご確認いただきたいこと（公開前）**
 *   Jグランツの公開データを**有料記事に載せてよいか**（利用条件）。
 *   サイトに無料で出すのと、有料の記事に入れるのは別の話になり得ます。
 *   クラウド側からは外のページを開けないので、ここでは確かめられていません。
 *   **確かめるまで公開しないでください。**
 *
 * ⚠ **記号を使いません。**noteの本文は貼り付けで壊れます
 *   （## や ** が文字のまま残り、2026-09-07 には半角英数と改行が消えた）。
 *   だから見出しは行と余白だけで見せます。
 *
 * 使い方
 *   node tools/売り物_締切カレンダーを組む.mjs
 *   → note原稿/売り物_補助金カレンダー_YYYY-MM.txt
 *
 * ⚠ **有料の線は、こちらでは引けません。**原稿の中に
 *   「ここから先は有料」という1行を入れてあるので、note の編集画面で
 *   その行に線を置いてください。**公開ボタンは常務が押します。**
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { 割合を読む } from './補助金のページを作る.mjs'

const ここ = dirname(fileURLToPath(import.meta.url))
const 作業場 = join(ここ, '..')

/**
 * 値段 ¥300 〔クロ決定〕
 *   ・¥100 … 相場だが、公的データの整理としては安く見え、逆に中身を疑われる
 *   ・¥300 … 「缶コーヒー1本」。総務の方が稟議なしで自腹で買える上限に近い
 *   ・¥500以上 … 無料で同じ情報が見られると分かった時点で、高いと感じる
 *   **1人目を作るための値段であって、利益を作るための値段ではない。**
 */
const 値段 = 300

const 今日 = new Date().toLocaleDateString('sv-SE', { timeZone: 'Asia/Tokyo' })
const [年, 月, 日] = 今日.split('-')
const 和文の日付 = `${年}年${Number(月)}月${Number(日)}日`
const 残り = 締切 =>
  Math.round((new Date(締切 + 'T00:00:00+09:00') - new Date(今日 + 'T00:00:00+09:00')) / 86400000)
const 円 = n => '¥' + Math.round(n).toLocaleString('ja-JP')

/** 上限額は0で入っていることがある。**0を「上限0円」と書かない** */
const 上限 = 額 => (額 ? `上限 ${円(額)}` : '上限は未公表')

/**
 * 自己負担の目安。**きれいに読める補助率のときだけ出す。**
 * 読めないものを当てずっぽうで数字にすると、読者が自己負担を見誤る。
 */
const 自己負担 = k => {
  const 率 = 割合を読む(k.詳細?.補助率)
  if (!率 || !k.上限額) return null
  const 事業費 = k.上限額 / 率
  return `上限まで使う場合、事業費は約${円(事業費)}、自己負担は約${円(事業費 - k.上限額)}`
}

const 一覧 = JSON.parse(readFileSync(join(作業場, 'データ', '補助金_掲載済み.json'), 'utf8')).掲載 ?? []
const 受付中 = 一覧
  .filter(k => k.締切 && 残り(k.締切) >= 0)
  .sort((a, b) => a.締切.localeCompare(b.締切))

if (受付中.length < 20) {
  console.error(`受付中が${受付中.length}件しかありません。売り物にはしません。`)
  process.exit(1)
}

const 地域名 = k => k.地域 ?? k.対象地域 ?? '全国'
const 全国のもの = 受付中.filter(k => 地域名(k) === '全国')
const 都道府県ごと = new Map()
for (const k of 受付中) {
  const g = 地域名(k)
  if (g === '全国') continue
  if (!都道府県ごと.has(g)) 都道府県ごと.set(g, [])
  都道府県ごと.get(g).push(k)
}
// 件数の多い順ではなく、五十音で。探すときに使う順序で並べる
const 並び = [...都道府県ごと.keys()].sort((a, b) => a.localeCompare(b, 'ja'))
// ⚠ 「複数の都道府県」という区分が混ざる。**これを1県として数えない**
const 県の数 = 並び.filter(g => /[都道府県]$/.test(g) && g !== '複数の都道府県').length

const 行 = []
const 足す = (...xs) => 行.push(...xs)

// ── 無料で読める側 ──────────────────────────────────────────
足す(
  `${年}年${Number(月)}月版　補助金の締切カレンダー（都道府県別）`,
  '',
  `${和文の日付} 時点で受付中のものを、締切の近い順に並べました。`,
  '',
  `受付中　${受付中.length}件`,
  `30日以内に締切　${受付中.filter(k => 残り(k.締切) <= 30).length}件`,
  `全国で使えるもの　${全国のもの.length}件`,
  `地域が決まっているもの　${受付中.length - 全国のもの.length}件（${県の数}都道府県＋複数県にまたがるもの）`,
  '',
  '',
  'この記事は何か',
  '',
  '中小企業の総務・管理部門の方が、自社で使えそうな補助金の締切を',
  '見落とさないための一覧です。1件ずつに、締切までの残り日数、上限額、',
  '読める場合は自己負担の目安、そして公式ページへのリンクを付けています。',
  '',
  '',
  'はじめに、正直に書いておきます',
  '',
  '元にしているのは、デジタル庁「Jグランツ」の公開データです。',
  '同じ情報は、公式サイトで誰でも無料で見られます。',
  '',
  `${値段}円をいただくのは、データそのものではありません。`,
  '都道府県ごとに分けて、締切の近い順に並べ、上限額と自己負担の目安と、',
  '締切から逆算した段取りを添えて、1本にまとめたことに対してです。',
  '',
  '公式サイトで探すと、地域や用途で絞り込みながら1件ずつ開くことになります。',
  'この記事は、その作業を先に済ませてあります。',
  '',
  'なお、業種が限られるもの（農林水産・エネルギー・運輸など）も混じります。',
  '名称と一言を読めば見分けがつくようにしてあります。すべてが自社に使える、',
  'という書き方はしていません。',
  '',
  '',
  'まず、無料で読める分',
  '',
  '全国で使えるもののうち、締切が近く、上限額と説明が公表されている5件です。',
  '',
)

// ⚠ **無料の5件は、締切順そのままでは選ばない。**
// 上限額が未公表で説明も無いものが並ぶと、中身が薄く見える。
// 嘘は書かないが、**いちばん分かりやすいものを前に出すのは編集の仕事。**
// 足りなければ締切順で埋める（数合わせのために嘘の条件を作らない）。
const 分かりやすい = 全国のもの.filter(k => k.上限額 && k.詳細?.一言)
const 見本 = [...分かりやすい, ...全国のもの.filter(k => !分かりやすい.includes(k))].slice(0, 5)
for (const k of 見本) {
  const 日 = 残り(k.締切)
  足す(
    `締切 ${k.締切}（あと${日}日）`,
    k.名称,
    `${上限(k.上限額)}`,
    ...(k.詳細?.一言 ? [k.詳細.一言] : []),
    k.出典,
    '',
  )
}

足す(
  '',
  'この続きに、残りの全件を入れています。',
  '',
  `・全国で使えるもの　${全国のもの.length}件（締切の近い順）`,
  `・都道府県ごと　${並び.join('、')}`,
  '・締切から逆算した段取り（いつ動き出せばよいか）',
  '',
  '',
  'ここから先は有料',
  '',
  '',
)

// ── 有料の側 ───────────────────────────────────────────────
足す(
  '締切から逆算した段取り',
  '',
  '補助金でいちばん多い失敗は、制度を知らなかったことではなく、',
  '知っていたのに間に合わなかったことです。目安はこうです。',
  '',
  '締切の30日前　公募要領を読み、対象になるかを確かめる',
  '締切の21日前　見積書を取りはじめる（複数社が要る制度があります）',
  '締切の14日前　社内の稟議を出す',
  '締切の7日前　申請の入力を終える（GビズIDの取得に数日かかることがあります）',
  '',
  'GビズIDプライムは、申請から発行まで日数がかかります。',
  'まだお持ちでなければ、締切に関係なく今日申し込んでおくのが安全です。',
  '',
  '',
  `全国で使えるもの　${全国のもの.length}件`,
  '',
)

const 一件ぶん = k => {
  const 日 = 残り(k.締切)
  const 負担 = 自己負担(k)
  const 出 = [
    `締切 ${k.締切}（あと${日}日）`,
    k.名称,
    `${上限(k.上限額)}　補助率 ${k.詳細?.補助率 ?? '公募要領をご確認ください'}`,
  ]
  if (負担) 出.push(負担)
  if (k.詳細?.一言) 出.push(k.詳細.一言)
  出.push(k.出典, '')
  return 出
}

for (const k of 全国のもの) 足す(...一件ぶん(k))

for (const 県 of 並び) {
  const ks = 都道府県ごと.get(県).sort((a, b) => a.締切.localeCompare(b.締切))
  足す('', `${県}　${ks.length}件`, '')
  for (const k of ks) 足す(...一件ぶん(k))
}

足す(
  '',
  'おわりに',
  '',
  'この一覧は、デジタル庁「Jグランツ」の公開データを毎朝取り直して作っています。',
  '受付が終わったもの、締切が変わったものは、そのつど反映しています。',
  '',
  '毎朝の最新版は、こちらで無料で見られます。',
  'https://soumu-choice.com/hojo/',
  '',
  '締切が近づいたときだけお知らせする無料のアラートもあります。',
  'https://soumu-choice.com/alert/',
  '',
  `※ この記事の内容は ${今日} 時点のものです。`,
  '※ 申請の可否や金額は、必ず各制度の公募要領と公式ページでご確認ください。',
)

const 出す先 = join(作業場, 'note原稿')
if (!existsSync(出す先)) mkdirSync(出す先, { recursive: true })
const 先 = join(出す先, `売り物_補助金カレンダー_${年}-${月}.txt`)
writeFileSync(先, 行.join('\n') + '\n', 'utf8')

const 字数 = 行.join('\n').length
console.log(`原稿ができました：note原稿/売り物_補助金カレンダー_${年}-${月}.txt`)
console.log(`　${受付中.length}件（全国 ${全国のもの.length}／都道府県 ${並び.length}）・約${字数.toLocaleString('ja-JP')}字`)
console.log(`　値段は ${円(値段)} の買い切り（クロ決定）。`)
console.log('　⚠ 「ここから先は有料」の行に、noteの編集画面で線を置いてください。')
console.log('　⚠ 公開の前に、Jグランツの公開データを有料記事に載せてよいかをご確認ください。')
